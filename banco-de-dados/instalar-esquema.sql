-- Instalação limpa do Espelho Meu a partir de criar.sql e 001-credenciais.sql.
-- Execute como script (F5) no usuário Oracle configurado no Render.
-- O inventário inicial bloqueia a execução em esquemas que já contêm objetos do projeto.

WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

SELECT SYS_CONTEXT('USERENV', 'SESSION_USER') AS usuario,
       SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS esquema
FROM DUAL;

DECLARE
    objetos_existentes NUMBER;
BEGIN
    IF SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') <> SYS_CONTEXT('USERENV', 'SESSION_USER') THEN
        RAISE_APPLICATION_ERROR(-20001, 'Conecte diretamente ao esquema do Espelho Meu.');
    END IF;

    SELECT COUNT(*)
    INTO objetos_existentes
    FROM USER_OBJECTS
    WHERE OBJECT_NAME IN (
        'T_EM_USUARIO', 'SQ_USUARIO', 'T_EM_PERFIL_CABELO',
        'SQ_PERFIL_CABELO', 'T_EM_PERFIL_MAQUIAGEM', 'SQ_PERFIL_MAQUIAGEM',
        'T_EM_CONSULTORIA_CAPILAR', 'SQ_CONSULTORIA_CAPILAR', 'T_EM_CONSULTORIA_MAQUIAGEM',
        'SQ_CONSULTORIA_MAQUIAGEM', 'T_EM_CORTE', 'SQ_CORTE',
        'T_EM_COR', 'SQ_COR', 'T_EM_PENTEADO',
        'SQ_PENTEADO', 'T_EM_RECOMENDACAO_CORTE', 'SQ_RECOMENDACAO_CORTE',
        'T_EM_RECOMENDACAO_COR', 'SQ_RECOMENDACAO_COR', 'T_EM_RECOMENDACAO_PENTEADO',
        'SQ_RECOMENDACAO_PENTEADO', 'T_EM_PRODUTO', 'SQ_PRODUTO',
        'T_EM_MAQUIAGEM', 'SQ_MAQUIAGEM', 'T_EM_REC_COT_PRO',
        'T_EM_REC_COR_PRO', 'T_EM_REC_PEN_PRO', 'T_EM_RECOMENDACAO_MAQUIAGEM',
        'SQ_RECOMENDACAO_MAQUIAGEM', 'T_EM_AVALIACAO', 'SQ_AVALIACAO',
        'T_EM_SIMULACAO', 'SQ_SIMULACAO', 'T_EM_FAVORITOS',
        'SQ_FAVORITOS', 'T_EM_CREDENCIAL'
    );

    IF objetos_existentes > 0 THEN
        RAISE_APPLICATION_ERROR(-20002, 'Já existem objetos do Espelho Meu. Verifique o esquema antes de instalar.');
    END IF;
END;
/

