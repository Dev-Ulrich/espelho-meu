CREATE TABLE T_EM_CREDENCIAL (
    ID_USUARIO NUMBER(10) NOT NULL,
    DS_HASH VARCHAR2(255 CHAR) NOT NULL,
    DS_ROLE VARCHAR2(10 CHAR) DEFAULT 'USER' NOT NULL,
    CONSTRAINT CREDENCIAL_PK PRIMARY KEY (ID_USUARIO),
    CONSTRAINT CREDENCIAL_USUARIO_FK FOREIGN KEY (ID_USUARIO)
        REFERENCES T_EM_USUARIO (ID_USUARIO) ON DELETE CASCADE,
    CONSTRAINT CREDENCIAL_ROLE_CK CHECK (DS_ROLE IN ('USER', 'ADMIN'))
);
