CREATE TABLE T_EM_CONSULTA_GUIADA (
    ID_CONSULTA VARCHAR2(36 CHAR) PRIMARY KEY,
    ID_USUARIO NUMBER(10) NOT NULL REFERENCES T_EM_USUARIO (ID_USUARIO) ON DELETE CASCADE,
    DS_AREA VARCHAR2(10 CHAR) NOT NULL CHECK (DS_AREA IN ('cabelo', 'maquiagem')),
    DS_RESULTADO CLOB NOT NULL,
    NR_LIMITE NUMBER(1) NOT NULL CHECK (NR_LIMITE BETWEEN 0 AND 3),
    BL_FOTO BLOB
);

CREATE INDEX EM_CONS_GUIADA_USUARIO_IX ON T_EM_CONSULTA_GUIADA (ID_USUARIO);

CREATE TABLE T_EM_PREVIA_CONSULTA (
    ID_CONSULTA VARCHAR2(36 CHAR) NOT NULL REFERENCES T_EM_CONSULTA_GUIADA (ID_CONSULTA) ON DELETE CASCADE,
    ID_CARTAO VARCHAR2(180 CHAR) NOT NULL,
    DS_ESTILO VARCHAR2(1000 CHAR) NOT NULL,
    DS_ESTADO VARCHAR2(12 CHAR) NOT NULL CHECK (DS_ESTADO IN ('QUEUED', 'RUNNING', 'READY', 'RETRYABLE', 'UNCERTAIN')),
    DT_ATUALIZACAO TIMESTAMP NOT NULL,
    BL_PREVIA BLOB,
    CONSTRAINT EM_PREVIA_CONSULTA_PK PRIMARY KEY (ID_CONSULTA, ID_CARTAO)
);

CREATE INDEX EM_PREVIA_FILA_IX ON T_EM_PREVIA_CONSULTA (DS_ESTADO, DT_ATUALIZACAO);
